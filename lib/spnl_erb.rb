# frozen_string_literal: true
gem "erb", "= 2.2.3" if defined?(Gem)
require "erb"
require "ripper"

module SpnlErb
  VERSION = "0.2.0"

  def self.identifier!(name, constant: false)
    pattern = constant ? /\A[A-Z]\w*(?:::[A-Z]\w*)*\z/ : /\A[a-z_]\w*[!?]?\z/
    raise ArgumentError, "invalid Ruby identifier: #{name.inspect}" unless name.to_s.match?(pattern)
    name
  end

  # Only actual @ivar tokens are rewritten; strings, comments and regexps stay intact.
  def self.localize(source)
    Ripper.lex(source).map { |_pos, type, text, _state| type == :on_ivar ? text.delete_prefix("@") : text }.join
  end

  def self.attributes(template)
    src = ERB.new(template, trim_mode: "-").src
    Ripper.lex(src).select { |_, type, _, _| type == :on_ivar }.map { |_, _, text, _| text.delete_prefix("@") }.uniq
  end

  def self.compile_body(template, var_name: "_out", escape_html: false)
    identifier!(var_name)
    # This compiler runs on CRuby. The generated method needs neither eval nor ERB at runtime.
    erb = ERB.new(template, trim_mode: "-", eoutvar: var_name)
    if escape_html
      raise ArgumentError, "use explicit ERB::Util.html_escape (h) in templates; implicit escaping changes ERB semantics"
    end
    erb.src
  end

  def self.compile_class(template, class_name:, attrs: [], method_name: "render", mode: :stateless, target_class: nil, source_path: nil)
    identifier!(method_name)
    attrs.each { |name| identifier!(name) }
    raise ArgumentError, "unknown mode: #{mode}" unless [:controller, :stateless, :instance].include?(mode)
    body = compile_body(template)
    body = localize(body) if mode == :stateless
    target = mode == :controller ? (target_class || "Controller") : class_name
    identifier!(target, constant: true)
    marker = source_path ? "#<SPINEL_SOURCE>#{source_path}:1\n" : ""
    raise ArgumentError, "source path must be one line" if source_path.to_s.match?(/[\r\n]/)
    definition = mode == :stateless ? "def self.#{method_name}(#{attrs.join(', ')})" : "def #{method_name}"
    init = if mode == :instance
      "  def initialize(#{attrs.join(', ')})\n" + attrs.map { |a| "    @#{a} = #{a}\n" }.join + "  end\n"
    else
      ""
    end
    kind = mode == :stateless ? "module" : "class"
    "# encoding: UTF-8\n# AUTO-GENERATED by spnl-erb #{VERSION}; do not edit\n#{kind} #{target}\n#{init}  #{definition}\n#{marker}" + body + "\n  end\nend\n"
  end
end
